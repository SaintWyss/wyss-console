/// xterm.js's `UnicodeV6.wcwidth`.
fn xterm6(c: u32) -> u8 {
    if c < 32 {
        return 0;
    }
    if c < 127 {
        return 1;
    }
    if c < 0xA0 {
        return 0;
    }
    if c < 65536 {
        if within(XTERM6_COMBINING, c) {
            return 0;
        }
        let wide = (0x1100..0x1160).contains(&c)
            || c == 0x2329
            || c == 0x232A
            || ((0x2E80..0xA4D0).contains(&c) && c != 0x303F)
            || (0xAC00..0xD7A4).contains(&c)
            || (0xF900..0xFB00).contains(&c)
            || (0xFE10..0xFE1A).contains(&c)
            || (0xFE30..0xFE70).contains(&c)
            || (0xFF00..0xFF61).contains(&c)
            || (0xFFE0..0xFFE7).contains(&c);
        return if wide { 2 } else { 1 };
    }
    if within(XTERM6_HIGH_COMBINING, c) {
        0
    } else if (0x20000..=0x2FFFD).contains(&c) || (0x30000..=0x3FFFD).contains(&c) {
        2
    } else {
        1
    }
}

/// 0, 1 or 2 columns.
pub fn of(table: Table, c: char) -> u8 {
    let c = c as u32;
    if table == Table::Xterm6 {
        return xterm6(c);
    }
    if c < 0x300 {
        return 1;
    }
    if within(ZERO, c) {
        0
    } else if within(WIDE, c) {
        2
    } else {
        1
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_tables_are_sorted_and_disjoint_so_the_search_is_sound() {
        for table in [WIDE, ZERO, XTERM6_COMBINING, XTERM6_HIGH_COMBINING] {
            for pair in table.windows(2) {
                assert!(pair[0].1 < pair[1].0, "{pair:x?}");
            }
            assert!(table.iter().all(|(lo, hi)| lo <= hi));
        }
        for &(lo, hi) in WIDE {
            assert!(!within(ZERO, lo) && !within(ZERO, hi));
        }
    }

    #[test]
    fn ascii_latin_cjk_emoji_and_marks() {
        for table in [Table::Xterm6, Table::Modern] {
            assert_eq!(of(table, 'a'), 1);
            assert_eq!(of(table, 'é'), 1);
            assert_eq!(of(table, '世'), 2);
            assert_eq!(of(table, '한'), 2);
            assert_eq!(of(table, '\u{0301}'), 0);
            assert_eq!(of(table, '\u{200D}'), 0);
            assert_eq!(of(table, '\u{FE0F}'), 0);
            assert_eq!(of(table, '─'), 1);
        }
        // The two tables differ where the window's renderer is older than the corpus: emoji.
        assert_eq!(of(Table::Modern, '😀'), 2);
        assert_eq!(of(Table::Xterm6, '😀'), 1);
        assert_eq!(of(Table::Xterm6, '\u{85}'), 0);
        assert_eq!(of(Table::Xterm6, '\u{303F}'), 1);
    }
}
