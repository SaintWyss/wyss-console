//! How many columns a character takes, by one of two tables.
//!
//! `Xterm6` is the table of the terminal the window draws with (xterm.js's default Unicode 6
//! provider, ported from its `UnicodeV6.ts`, MIT): what a repaint must agree with, because it is
//! that renderer that places the characters. `Modern` is a compact East Asian Wide / emoji table
//! like the one tmux uses; the reference corpus is compared under it. Controls never reach here.

#[derive(Clone, Copy, Debug, PartialEq, Eq, Default)]
pub enum Table {
    /// What the window's own terminal uses today.
    #[default]
    Xterm6,
    /// Emoji and recent East Asian ranges count as wide, like tmux and current terminals.
    Modern,
}

