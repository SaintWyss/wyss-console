/* Prints the libghostty-vt ABI facts that src/bin/wyss-console-native/ghostty.rs hard-codes; check-abi.sh compares them. */
#include <stdio.h>
#include <stddef.h>
#include <ghostty/vt.h>
int main(void) {
  printf("style=%zu cursor=%zu scroll=%zu mode=%zu rgb=%zu\n", sizeof(GhosttyStyle),
         sizeof(GhosttyRenderStateCursor), sizeof(GhosttyTerminalScrollViewport),
         sizeof(GhosttyTerminalModeConfig), sizeof(GhosttyColorRgb));
  printf("OPT_USERDATA=%d OPT_WRITE_PTY=%d OPT_COLOR_FOREGROUND=%d OPT_COLOR_BACKGROUND=%d OPT_COLOR_PALETTE=%d OPT_SCROLLBACK_MAX_LINES=%d\n",
         GHOSTTY_TERMINAL_OPT_USERDATA, GHOSTTY_TERMINAL_OPT_WRITE_PTY, GHOSTTY_TERMINAL_OPT_COLOR_FOREGROUND,
         GHOSTTY_TERMINAL_OPT_COLOR_BACKGROUND, GHOSTTY_TERMINAL_OPT_COLOR_PALETTE, GHOSTTY_TERMINAL_OPT_SCROLLBACK_MAX_LINES);
  printf("OPT_DEFAULT_CURSOR_STYLE=%d OPT_DEFAULT_CURSOR_BLINK=%d\n",
         GHOSTTY_TERMINAL_OPT_DEFAULT_CURSOR_STYLE, GHOSTTY_TERMINAL_OPT_DEFAULT_CURSOR_BLINK);
  printf("TDATA_VIEWPORT_ACTIVE=%d TDATA_MODE=%d SCROLL_BOTTOM=%d SCROLL_DELTA=%d MODE_DECCKM=%u\n",
         GHOSTTY_TERMINAL_DATA_VIEWPORT_ACTIVE, GHOSTTY_TERMINAL_DATA_MODE, GHOSTTY_SCROLL_VIEWPORT_BOTTOM,
         GHOSTTY_SCROLL_VIEWPORT_DELTA, (unsigned)GHOSTTY_MODE_DECCKM);
  printf("MODE_BRACKETED_PASTE=%u\n", (unsigned)GHOSTTY_MODE_BRACKETED_PASTE);
  printf("RDATA_COLS=%d RDATA_ROWS=%d RDATA_DIRTY=%d RDATA_ROW_ITERATOR=%d RDATA_CURSOR=%d ROW_DATA_CELLS=%d\n",
         GHOSTTY_RENDER_STATE_DATA_COLS, GHOSTTY_RENDER_STATE_DATA_ROWS, GHOSTTY_RENDER_STATE_DATA_DIRTY,
         GHOSTTY_RENDER_STATE_DATA_ROW_ITERATOR, GHOSTTY_RENDER_STATE_DATA_CURSOR, GHOSTTY_RENDER_STATE_ROW_DATA_CELLS);
  printf("CELLS_RAW=%d CELLS_STYLE=%d CELLS_BG_COLOR=%d CELLS_FG_COLOR=%d CELLS_HAS_STYLING=%d CELLS_GRAPHEMES_UTF8=%d CELL_DATA_WIDE=%d\n",
         GHOSTTY_RENDER_STATE_ROW_CELLS_DATA_RAW, GHOSTTY_RENDER_STATE_ROW_CELLS_DATA_STYLE,
         GHOSTTY_RENDER_STATE_ROW_CELLS_DATA_BG_COLOR, GHOSTTY_RENDER_STATE_ROW_CELLS_DATA_FG_COLOR,
         GHOSTTY_RENDER_STATE_ROW_CELLS_DATA_HAS_STYLING, GHOSTTY_RENDER_STATE_ROW_CELLS_DATA_GRAPHEMES_UTF8, GHOSTTY_CELL_DATA_WIDE);
  printf("gridref=%zu selection=%zu selbuf=%zu coord=%zu string=%zu\n", sizeof(GhosttyGridRef), sizeof(GhosttySelection),
         sizeof(GhosttySelectionBuffer), sizeof(GhosttyPointCoordinate), sizeof(GhosttyString));
  printf("SEARCH_DATA_TOTAL_MATCHES=%d SEARCH_DATA_SELECTED_INDEX=%d SEARCH_DATA_SELECTED_MATCH=%d SEARCH_DATA_VIEWPORT_MATCHES=%d\n",
         GHOSTTY_SEARCH_DATA_TOTAL_MATCHES, GHOSTTY_SEARCH_DATA_SELECTED_INDEX, GHOSTTY_SEARCH_DATA_SELECTED_MATCH,
         GHOSTTY_SEARCH_DATA_VIEWPORT_MATCHES);
  printf("SEARCH_OPT_NEEDLE=%d SEARCH_OPT_SELECT_NEXT=%d SEARCH_OPT_SELECT_PREV=%d POINT_TAG_VIEWPORT=%d\n", GHOSTTY_SEARCH_OPT_NEEDLE,
         GHOSTTY_SEARCH_OPT_SELECT_NEXT, GHOSTTY_SEARCH_OPT_SELECT_PREV, GHOSTTY_POINT_TAG_VIEWPORT);
  return 0;
}
