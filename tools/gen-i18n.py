#!/usr/bin/env python3
import json, pathlib, re, sys

here = pathlib.Path(__file__).resolve().parent.parent
NATIVE = here / "src/bin/wyss-console-native"


def used():
    found = {}
    pat = re.compile(r'\b(?:t!|trf|tr)\(\s*"((?:[^"\\]|\\.)*)"')
    for f in sorted(NATIVE.rglob("*.rs")):
        if f.name in ("i18n_table.rs", "i18n.rs"):
            continue
        for m in pat.finditer(f.read_text()):
            found[json.loads('"' + m.group(1) + '"')] = f.name
    return found


def rust(s):
    return json.dumps(s, ensure_ascii=False)


def main():
    source = json.loads((here / "i18n/es.json").read_text())
    es = source["sentences"]
    rows, missing = [], []
    for en in sorted(used()):
        if en in es:
            rows.append((en, es[en]))
        else:
            missing.append(en)
    if missing:
        sys.exit("Faltan traducciones:\n  " + "\n  ".join(missing))
    unused = sorted(set(es) - set(used()))
    if unused:
        sys.exit("Traducciones sin uso en i18n/es.json:\n  " + "\n  ".join(unused))
    out = "// Generated by tools/gen-i18n.py from i18n/es.json. Do not edit.\n"
    out += "pub const ES: &[(&str, &str)] = &[\n"
    for en, sp in rows:
        out += f"    ({rust(en)}, {rust(sp)}),\n"
    out += "];\n"
    incoming = source["incoming"]
    out += "pub const INCOMING_ES: &[(&str, &str)] = &[\n"
    for en, sp in sorted(incoming.items()):
        out += f"    ({rust(en)}, {rust(sp)}),\n"
    out += "];\n"
    target = NATIVE / "i18n_table.rs"
    if "--check" in sys.argv:
        if not target.exists() or target.read_text() != out:
            sys.exit(f"{target.name} is out of date: run tools/gen-i18n.py")
        print(f"ok ({len(rows)} sentences)")
        return
    target.write_text(out)
    print(f"{len(rows)} sentences")


main()
